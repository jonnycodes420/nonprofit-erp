// BUILD-86 C.2 — THE NOTE FIXTURE.
//
// Twenty rendered notes, in a row, so a human can read them and hear whether
// any sound like a machine. The brief asks for exactly this and asks that the
// diff be REVIEWED rather than asserted byte-for-byte, because the failure
// mode here is not "wrong" — it is "correct and lifeless", and no assertion
// catches that.
//
//   node scripts/build86-notes-fixture.js      → docs/build86/notes.txt
// Pure: no server, no DB, no clock (the date is pinned).
// Loopback-free (script-guards class: PURE).
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "docs", "build86", "notes.txt");
const NOW = Date.parse("2026-09-16T12:00:00Z");
const day = n => new Date(NOW - n * 86400000).toISOString();

const HOA = { giver_singular: "sponsor", giver_plural: "sponsors" };

const th = rows => ({ list: rows.map(r => ({ donorName: r[0], overdue: true, overdueDays: r[1], nextStep: { label: r[2] } })) });
const open = rows => ({ list: rows.map(n => ({ donorName: n, overdue: false })) });
const dr = names => ({ list: names.map(n => ({ donorName: n })) });
const ar = (names, days = 2) => names.map(n => ({ donor_name: n, first_failed_at: day(days) }));

const CASES = [
  ["nothing at all", {}],
  ["one open, nothing late", { threads: open(["Kip Lee"]) }],
  ["three open, nothing late", { threads: open(["Kip Lee", "Ana Diaz", "Tom Fairweather"]) }],
  ["one late, she owes a report", { threads: th([["Margaret Chen", 7, "Send the import report"]]) }],
  ["one late, yesterday", { threads: th([["Diana Torres", 1, "Send the photos"]]) }],
  ["one late, a call she meant to make", { threads: th([["Robert Harmon", 14, "Call about the gala"]]) }],
  ["one late, a bare call", { threads: th([["Ruth Alderman", 3, "Call"]]) }],
  ["one late, a follow-up", { threads: th([["Nate Brooks", 11, "Follow up on the studio visit"]]) }],
  ["one late, a thank-you", { threads: th([["Ivy Marchetti", 4, "Send thank-you note"]]) }],
  ["one late, months", { threads: th([["Caleb Osei", 80, "Send the proposal"]]) }],
  ["one late, an unrecognised step", { threads: th([["Lena Whitfield", 22, "Revisit the naming question"]]) }],
  ["one late, an organisation", { threads: th([["Sunrise Foundation", 9, "Send the budget"]]) }],
  ["three late", { threads: th([["Margaret Chen", 11, "Send the report"], ["Robert Harmon", 3, "Call"], ["Diana Torres", 2, "Call"]]) }],
  ["eight late", { threads: th(Array.from({ length: 8 }, (_, i) => [`Donor ${i + 1}`, 12 - i, "Follow up on the ask"])) }],
  ["drift alone", { drift: dr(["Otis Grange", "Ana Diaz"]) }],
  ["one card failed", { atRisk: ar(["Rob Delaney"]) }],
  ["two cards failed", { atRisk: ar(["Rob Delaney", "Kip Lee"]) }],
  ["a card that failed a month ago", { atRisk: ar(["Old Failure"], 40) }],
  ["everything, Steward's words", { threads: th([["Margaret Chen", 7, "Send the import report"]]), drift: dr(["Otis Grange", "Ana Diaz"]), atRisk: ar(["Rob Delaney", "Kip Lee"]) }],
  ["everything, Heart of Africa's words", { threads: th([["Margaret Chen", 7, "Send the import report"]]), drift: dr(["Otis Grange", "Ana Diaz"]), atRisk: ar(["Rob Delaney", "Kip Lee"]), vocabulary: HOA }],
];

(async () => {
  const { homeNote } = await import("../shared/homeNote.js");
  const width = Math.max(...CASES.map(c => c[0].length));
  const lines = [
    "BUILD-86 C.2 — the note at the top of her morning, twenty ways.",
    "",
    "Generated by scripts/build86-notes-fixture.js. Pinned to 2026-09-16, so a",
    "regeneration only moves when the GRAMMAR moves. Read them in a row and",
    "listen for one that sounds like software; that is the test this file is.",
    "",
    "The rules being heard: lead with the person when one thing is late and",
    "with the count when several, still naming who has waited longest. Time in",
    "words, never \"day 7\". Numbers under ten spelled. No colons, no em dashes.",
    "Her vocabulary. And nothing waiting is a good morning, not an empty state.",
    "",
    "=".repeat(78), "",
  ];
  for (const [label, input] of CASES) {
    lines.push(`${label.padEnd(width)}  ${homeNote(input, NOW)}`);
  }
  lines.push("");
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"));
  console.log(lines.join("\n"));
})();
